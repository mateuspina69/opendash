uint32_t jpCodepoint(int font, int g) {
    if (font == 0 && g >= 0 && g < 834) return kFont0[g];
    if (font == 1 && g >= 0 && g < 804) return kFont1[g];
    return 0;
}

int jpGlyphOf(uint32_t cp) {
    if (cp == 0x20) return 0x20;
    for (int g = 0; g < 834; ++g)
        if (kFont0[g] == cp) return g;
    return -1;
}

std::string jpGlyphText(int font, int g) {
    const uint32_t c = jpCodepoint(font, g);
    std::string s;
    if (c == 0) return s;
    if (c < 0x80) {
        s += char(c);
    } else if (c < 0x800) {
        s += char(0xc0 | (c >> 6));
        s += char(0x80 | (c & 0x3f));
    } else {
        s += char(0xe0 | (c >> 12));
        s += char(0x80 | ((c >> 6) & 0x3f));
        s += char(0x80 | (c & 0x3f));
    }
    return s;
}

